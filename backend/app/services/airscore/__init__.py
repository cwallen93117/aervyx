# AirScore Python Port
# Faithful 1:1 port of Geoff Wong's AirScore (Perl) scoring engine
# Source: https://github.com/geoffwong/airscore
#
# Modules:
#   track_lib  - Geometry, Vincenty distance, coordinate transforms (TrackLib.pm)
#   route      - Shortest route through cylinders (Route.pm)
#   task       - Task distance calculations, remaining distance (Task.pm)
#   gap        - GAP scoring formula: validities, points allocation (Gap.pm)
